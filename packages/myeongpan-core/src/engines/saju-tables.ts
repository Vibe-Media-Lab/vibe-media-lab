export const JANGGAN: Record<string, string[]> = {
  '자': ['임', '계'],
  '축': ['기', '계', '신'],
  '인': ['갑', '병', '무'],
  '묘': ['을'],
  '진': ['무', '을', '계'],
  '사': ['병', '경', '무'],
  '오': ['정', '기'],
  '미': ['기', '정', '을'],
  '신': ['경', '임', '무'],
  '유': ['신'],
  '술': ['무', '신', '정'],
  '해': ['임', '갑'],
}

/** 지지의 본기(첫 번째 지장간) 반환 */
export function getMainJanggan(branch: string): string {
  return JANGGAN[branch]?.[0] ?? ''
}

// ============================================================
// 2) 십신 (十神) — 일간 vs target 천간 비교
// ============================================================

const GENERATES: Record<FiveElement, FiveElement> = {
  '목': '화',
  '화': '토',
  '토': '금',
  '금': '수',
  '수': '목',
}

const CONTROLS: Record<FiveElement, FiveElement> = {
  '목': '토',
  '화': '금',
  '토': '수',
  '금': '목',
  '수': '화',
}

/**
 * 일간 기준 십신 산출
 *
 * @param dayStem 일간 (예: '갑')
 * @param targetStem 대상 천간 (예: '병')
 * @returns 십신 이름 (비견/겁재/식신/상관/편재/정재/편관/정관/편인/정인)
 */
export function getSipsin(dayStem: string, targetStem: string): string {
  const day = STEMS[dayStem]
  const target = STEMS[targetStem]
  if (!day || !target) return ''

  const sameYinYang = day.yinYang === target.yinYang

  // 비겁 (같은 오행)
  if (day.element === target.element) {
    return sameYinYang ? '비견' : '겁재'
  }

  // 식상 (내가 생하는 오행)
  if (GENERATES[day.element] === target.element) {
    return sameYinYang ? '식신' : '상관'
  }

  // 재성 (내가 극하는 오행)
  if (CONTROLS[day.element] === target.element) {
    return sameYinYang ? '편재' : '정재'
  }

  // 관성 (나를 극하는 오행)
  if (CONTROLS[target.element] === day.element) {
    return sameYinYang ? '편관' : '정관'
  }

  // 인성 (나를 생하는 오행)
  if (GENERATES[target.element] === day.element) {
    return sameYinYang ? '편인' : '정인'
  }

  return ''
}

